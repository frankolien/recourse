#!/usr/bin/env node
// Emits typed address books so no downstream code hardcodes an address.
//
//   node ops/codegen.mjs                        the engine, from Arc testnet
//   node ops/codegen.mjs deployments/5042.json  the engine, from Arc mainnet
//
// The engine is generated from one chain, because it is a library compiled against one
// deployment. The phone is generated from every chain at once, because the phone lets
// whoever is holding it choose, and a chain it was not built with is a chain it cannot
// offer.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ZERO = "0x0000000000000000000000000000000000000000";

const read = (path) => JSON.parse(readFileSync(resolve(repoRoot, path), "utf8"));
const readOptional = (path) => {
  try {
    return read(path);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
};

const arcConfig = read("deployments/arc-config.json");

// --- the engine, one chain --------------------------------------------------
const inputArg = process.argv[2] ?? "deployments/arc-testnet.json";
const d = read(inputArg);
if (!(d.rpcUrl ?? arcConfig.rpcUrl)) {
  throw new Error(`${inputArg} has no rpcUrl and arc-config.json does not cover chain ${d.chainId}`);
}

// --- the phone, every chain -------------------------------------------------
// Order matters: the first is what a fresh install opens on.
const CHAINS = [
  {
    file: "deployments/arc-testnet.json",
    name: "Arc Testnet",
    // Testnet's endpoint and API predate a deployment file carrying its own.
    rpcUrl: arcConfig.rpcUrl,
    apiUrl: "https://api.frankolien.com",
    fxFile: "deployments/arc-testnet-fx.json",
  },
  {
    file: "deployments/5042.json",
    name: "Arc",
    apiUrl: "https://recourse-arc-mainnet-production.up.railway.app",
  },
];

const books = CHAINS.map((chain) => {
  const c = read(chain.file);
  // A venue belongs to one chain. Wiring a testnet pool into a mainnet build would
  // offer real money a venue holding play money, so the chain ids have to agree.
  const raw = chain.fxFile ? readOptional(chain.fxFile) : null;
  const fx = raw && raw.chainId === c.chainId ? raw : null;
  return {
    chainID: c.chainId,
    name: chain.name,
    rpcURL: c.rpcUrl ?? chain.rpcUrl,
    apiURL: chain.apiUrl,
    usdc: c.usdc,
    policyRegistry: c.policyRegistry ?? ZERO,
    yieldAdapter: c.yieldAdapter ?? ZERO,
    escrow: c.escrow ?? ZERO,
    settlementVault: c.settlementVault ?? ZERO,
    attestor: c.attestor ?? ZERO,
    treasury: c.treasury ?? ZERO,
    consumer: Boolean(c.escrow && c.policyRegistry && c.settlementVault),
    olienFactory: c.olien?.factory ?? null,
    fxRouter: fx?.router ?? null,
    eurc: fx?.eurc ?? null,
    fxPublic: fx?.public === true,
  };
});

const str = (v) => (v === null ? "nil" : JSON.stringify(v));

const bookLiteral = (b) =>
  [
    "        ChainBook(",
    `            chainID: ${b.chainID},`,
    `            name: ${JSON.stringify(b.name)},`,
    `            rpcURL: ${JSON.stringify(b.rpcURL)},`,
    `            apiURL: ${JSON.stringify(b.apiURL)},`,
    `            usdc: ${JSON.stringify(b.usdc)},`,
    `            policyRegistry: ${JSON.stringify(b.policyRegistry)},`,
    `            yieldAdapter: ${JSON.stringify(b.yieldAdapter)},`,
    `            escrow: ${JSON.stringify(b.escrow)},`,
    `            settlementVault: ${JSON.stringify(b.settlementVault)},`,
    `            attestor: ${JSON.stringify(b.attestor)},`,
    `            treasury: ${JSON.stringify(b.treasury)},`,
    `            consumer: ${b.consumer},`,
    `            olienFactory: ${str(b.olienFactory)},`,
    `            fxRouter: ${str(b.fxRouter)},`,
    `            eurc: ${str(b.eurc)},`,
    `            fxPublic: ${b.fxPublic}`,
    "        )",
  ].join("\n");

const engineBanner = `// GENERATED by ops/codegen.mjs from ${inputArg}. Do not edit by hand.`;
const phoneBanner = `// GENERATED by ops/codegen.mjs from ${CHAINS.map((c) => c.file).join(" and ")}. Do not edit by hand.`;

// Built as lines rather than one template literal, because Swift doc comments name
// symbols in backticks and a backtick would close the literal early.
const swift = [
  phoneBanner,
  "import Foundation",
  "",
  "/// One chain, as the app needs to know it.",
  "///",
  "/// Addresses a chain does not carry are zero rather than absent: a dozen places read",
  "/// them without validating them, and only the features that would call a contract",
  "/// need to care. Those read the flags below instead.",
  "struct ChainBook: Sendable, Equatable, Identifiable {",
  "    let chainID: UInt64",
  "    let name: String",
  "    let rpcURL: String",
  "    let apiURL: String",
  "    let usdc: String",
  "    let policyRegistry: String",
  "    let yieldAdapter: String",
  "    let escrow: String",
  "    let settlementVault: String",
  "    let attestor: String",
  "    let treasury: String",
  "    /// Whether this chain carries the buyer protection contracts.",
  "    let consumer: Bool",
  "    /// The Olien factory, where treasuries exist on this chain.",
  "    let olienFactory: String?",
  "    let fxRouter: String?",
  "    let eurc: String?",
  "    /// A venue can be deployed and still refuse every ordinary amount, which is",
  "    /// worse than not offering one, so this is separate from whether it exists.",
  "    let fxPublic: Bool",
  "",
  "    var id: UInt64 { chainID }",
  "    /// Arc mainnet is the only chain here where the dollars are dollars.",
  "    var isTestnet: Bool { chainID != 5042 }",
  "}",
  "",
  "/// The chain this session is pointed at.",
  "///",
  "/// These were compile time constants until the app could be switched between",
  "/// chains. They are computed now, so the switch changes what the whole app reads at",
  "/// once and nothing that reads an address had to learn that the chain can move.",
  "enum Deployment {",
  "    /// Every chain this build can be pointed at. The first is what a fresh install",
  "    /// opens on, and it is a testnet, because opening a money app on real money by",
  "    /// default is a decision nobody made.",
  "    static let books: [ChainBook] = [",
  books.map(bookLiteral).join(",\n"),
  "    ]",
  "",
  "    static let primary = books[0]",
  "",
  "    static var current: ChainBook { NetworkStore.resolved() }",
  "",
  "    static var chainID: UInt64 { current.chainID }",
  "    static var rpcURL: String { current.rpcURL }",
  "    static var apiURL: String { current.apiURL }",
  "    static var usdc: String { current.usdc }",
  "    static var policyRegistry: String { current.policyRegistry }",
  "    static var yieldAdapter: String { current.yieldAdapter }",
  "    static var escrow: String { current.escrow }",
  "    static var settlementVault: String { current.settlementVault }",
  "    static var attestor: String { current.attestor }",
  "    static var treasury: String { current.treasury }",
  "    static var consumer: Bool { current.consumer }",
  "    static var olienFactory: String? { current.olienFactory }",
  "    static var fxRouter: String? { current.fxRouter }",
  "    static var eurc: String? { current.eurc }",
  "    static var fxPublic: Bool { current.fxPublic }",
  "}",
  "",
].join("\n");

const TARGETS = [
  {
    path: "engine/src/addresses.ts",
    render: () => `${engineBanner}
export const chainId = ${d.chainId};

export const addresses = {
  usdc: "${d.usdc}",
  policyRegistry: "${d.policyRegistry ?? ZERO}",
  yieldAdapter: "${d.yieldAdapter ?? ZERO}",
  escrow: "${d.escrow ?? ZERO}",
  settlementVault: "${d.settlementVault ?? ZERO}",
} as const;

export type ContractName = keyof typeof addresses;
`,
  },
  { path: "mobile/Recourse/Generated/Deployment.swift", render: () => swift },
];

for (const t of TARGETS) {
  const out = join(repoRoot, t.path);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, t.render());
  console.log(`wrote ${t.path}`);
}
